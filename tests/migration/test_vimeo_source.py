def test_caption_selection_prefers_active_human_newest():
    raw = texttracks(("fr",)) + [
        {"uri": "/videos/1/texttracks/5", "id": 5, "type": "captions", "language": "fr", "active": True, "link": "l5", "name": "auto", "provenance": "autogenerated"},
        {"uri": "/videos/1/texttracks/950", "id": 950, "type": "captions", "language": "fr", "active": False, "link": "l950", "name": "x"},
        {"uri": "/videos/1/texttracks/9", "id": 9, "type": "chapters", "language": "fr", "active": True, "link": "l9"},
    ]
    chosen, notes = select_captions(raw)
    assert chosen["fr"].vimeo_track_id == "900" and notes


def test_caption_source_prefers_srt_else_vtt():
    c = select_captions(texttracks(("fr",)))[0]["fr"]
    resolve_caption_source(FakeVimeo(srt=True), c)
    assert c.source_format == "srt" and "src" in c.source_url
    c2 = select_captions(texttracks(("fr",)))[0]["fr"]
