def test_hls_audio_separates_embedded_original_from_six_dubbed_tracks():
    tracks = parse_hls_audio(manifest(), "https://cdn.example/a/b/master.m3u8")
    assert len(tracks) == 7
    d = classify_audio(tracks)
    assert sorted(d.tracks) == ["en", "es", "fr", "it", "pt", "ro"]
    assert len(d.original) == 1 and d.original[0].default and d.original[0].language == "en"
    # the dubbed English is a different rendition from the embedded English audio
    assert d.tracks["en"].rendition_key == KEYS["en"] != d.original[0].rendition_key
    assert d.tracks["fr"].playlist_url.startswith("https://cdn.example/")
    assert d.tracks["fr"].name == "French"


def test_repeated_dubbed_language_is_reported_not_silently_merged():
    text = manifest() + '\n#EXT-X-MEDIA:TYPE=AUDIO,NAME="Fr2",CHARACTERISTICS="public.translation.dubbed",LANGUAGE="fr",URI="../v2/playlist/av/dead/avf/b/media.m3u8"'
    d = classify_audio(parse_hls_audio(text, "https://cdn.example/a/master.m3u8"))
    assert len(d.duplicates) == 1


def test_plan_reports_each_missing_audio_and_caption_language():
    api = FakeVimeo(audio_langs=("en", "fr", "it", "pt", "es"), caption_langs=("en", "fr"))
    plan = build_video_plan(api, api.videos["111"])
    assert plan.missing_audio == ["ro"]
    assert plan.missing_captions == ["it", "pt", "ro", "es"]
    stages = {(p["stage"], p["language"]) for p in plan.problems}
    assert ("AUDIO_DISCOVERY", "ro") in stages and ("CAPTION_DISCOVERY", "es") in stages


