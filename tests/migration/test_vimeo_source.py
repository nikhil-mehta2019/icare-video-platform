def test_vimeoapi_retries_then_raises():
    calls = []

    class S:
        def get(self, url, **kw):
            calls.append(url)
            return Resp({}, 429)

    api = VimeoApi(session=S(), sleep=lambda s: None)
    with pytest.raises(Exception):
        api.get_json("/videos/1")
    assert len(calls) == 4
