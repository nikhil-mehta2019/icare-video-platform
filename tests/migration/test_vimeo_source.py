class Resp:
    def __init__(self, data, status=200):
        self._d, self.status_code, self.text = data, status, str(data)
        self.headers = {}

    def json(self):
        return self._d


def test_folder_discovery_paginates_and_recurses(monkeypatch):
    pages = {
        "https://api.vimeo.com/me/projects/1/items?per_page=100": {
            "data": [{"type": "video", "video": video_json("10")},
                     {"type": "folder", "folder": {"uri": "/users/1/projects/2", "name": "Sub"}}],
            "paging": {"next": "/me/projects/1/items?per_page=100&page=2"}},
        "https://api.vimeo.com/me/projects/1/items?per_page=100&page=2": {"data": [{"type": "video", "video": video_json("11")}], "paging": {}},
        "https://api.vimeo.com/me/projects/2/items?per_page=100": {"data": [{"type": "video", "video": video_json("12")}], "paging": {}},
    }
    monkeypatch.setattr(vimeo_service.requests, "get", lambda url, **kw: Resp(pages[url]))
    items = vimeo_service.get_vimeo_folder_videos("1")
    assert sorted(i["video"]["uri"] for i in items) == ["/videos/10", "/videos/11", "/videos/12"]
    assert {i["video"]["uri"]: i["folder_name"] for i in items}["/videos/12"] == "Sub"


def test_duplicate_vimeo_ids_are_dropped_and_reported():
    items = [{"video": video_json("10")}, {"video": video_json("11")}, {"video": video_json("10")}]
    unique, dups = dedupe_videos(items)
    assert [i["video"]["uri"] for i in unique] == ["/videos/10", "/videos/11"]
    assert dups == ["10"]


